import assert from 'node:assert/strict';
import {applyCommand,emptyJourney,nextTask,reviewDate,localDay} from '../lib/personal/domain.ts';
import {sampleJourney} from '../lib/personal/examples.ts';
import {questions,applicableQuestions,validAnswer} from '../lib/personal/assessment.ts';
import {resultLabel,detailLabel,categories,startingPoint,safeOrigin} from '../lib/personal/footprint.ts';
const day=localDay('UTC'),base=sampleJourney('weekly','UTC');
base.answers={household:{value:'2',quality:'supplied'}};
base.startingPoint=structuredClone(base.footprint);
const edit=applyCommand(base,{type:'assessmentDraft',patch:{step:'household',origin:'/personal/today'},answer:{id:'household',value:{value:'3',quality:'approximate'}}},'draft-1',day);
for(const key of ['footprint','startingPoint','actions','checkIns','reviews','answers','firstSavedOn','nextReviewOn'])assert.deepEqual(edit[key],base[key],`draft preserves ${key}`);
assert.equal(edit.drafts.assessment.answers.household.value,'3');
assert.equal(edit.drafts.assessment.optional,true);
assert.equal(reviewDate(edit),reviewDate(base));
assert.equal(nextTask(edit,day).kind,nextTask(base,day).kind);
const again=applyCommand(edit,{type:'assessmentDraft',patch:{step:'diet'},answer:{id:'diet',value:{value:'',quality:'unknown'}}},'draft-2',day);
assert.equal(again.drafts.assessment.answers.household.value,'3');
assert.equal(again.drafts.assessment.id,edit.drafts.assessment.id);
assert.deepEqual(applyCommand(edit,{type:'assessmentDraft',patch:{step:'diet'}},'draft-1',day),edit,'idempotent duplicate event');
const empty=applyCommand(emptyJourney('UTC'),{type:'assessmentDraft',patch:{step:'household'}},'initial',day);
assert.equal(nextTask(empty,day).kind,'assessment');assert.equal(empty.drafts.assessment.optional,false);
const conditional={vehicle:{value:'No personal vehicle',quality:'supplied'},carDistance:{value:'120',quality:'supplied'}};
assert.ok(!applicableQuestions(conditional).some(q=>q.id==='carDistance'));assert.equal(conditional.carDistance.value,'120');
const distance=questions.find(q=>q.id==='carDistance');
assert.equal(validAnswer(distance,{value:'0',quality:'supplied'}),true);
assert.equal(validAnswer(distance,{value:'-1',quality:'supplied'}),false);
assert.equal(validAnswer(distance,{value:'',quality:'supplied'}),false);
assert.equal(validAnswer(distance,{value:'',quality:'unknown'}),true);
const r={id:'x',date:day,total:6.4,coverage:79.9,range:[5,8]};
assert.equal(resultLabel(r),'About 5.0–8.0');assert.equal(resultLabel({...r,coverage:80}),'About 6.4');
assert.equal(resultLabel({...r,range:undefined}),'About 6.4');
assert.equal(detailLabel({...r,coverage:99}),'Estimate detail: 95%');assert.equal(detailLabel({...r,coverage:100}),'Estimate detail: 100%');
assert.ok(categories(base,false).every(c=>c.value===undefined));assert.equal(startingPoint(empty,false),undefined);
assert.equal(safeOrigin('https://example.com'),'/personal/footprint');
console.log('Footprint checks passed: shared draft, preserved records/schedule, task priority, unknown/zero validation, conditional answers, uncertainty bands, fixture isolation.');
